    setting_value VARCHAR(1000),
    description   VARCHAR(255),
    act_yn        VARCHAR(1)   NOT NULL DEFAULT 'Y',
    reg_id        VARCHAR(50),
    reg_dtm       TIMESTAMP,
    mod_id        VARCHAR(50),
