SELECT 1,
       COALESCE((SELECT setting_value FROM app_setting WHERE setting_key = 'restaurant.name'), 'Restaurant'),
       COALESCE((SELECT setting_value FROM app_setting WHERE setting_key = 'restaurant.nameEn'), 'Restaurant'),
       'system', CURRENT_TIMESTAMP;

INSERT INTO branch (id, company_id, code, name, name_en, address, phone, reg_id, reg_dtm)
SELECT 1, 1, 'MAIN',
       COALESCE((SELECT setting_value FROM app_setting WHERE setting_key = 'restaurant.name'), 'Restaurant'),
       COALESCE((SELECT setting_value FROM app_setting WHERE setting_key = 'restaurant.nameEn'), 'Restaurant'),
       (SELECT setting_value FROM app_setting WHERE setting_key = 'restaurant.address'),
       (SELECT setting_value FROM app_setting WHERE setting_key = 'restaurant.phone'),
       'system', CURRENT_TIMESTAMP;

-- Identity columns were handed explicit values above, so the generators have
-- to be told where to carry on from.
ALTER TABLE company ALTER COLUMN id RESTART WITH 2;
ALTER TABLE branch  ALTER COLUMN id RESTART WITH 2;

