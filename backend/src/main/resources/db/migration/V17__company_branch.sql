-- ---------------------------------------------------------------------------
-- V17 — one shop becomes one of several
--
-- Nothing in this schema has ever said which restaurant a row belongs to,
-- because there has only ever been one. The moment there are two, every table
-- without that column holds rows belonging to nobody in particular, and every
-- query returns both shops' business to whoever asked first.
--
-- docs/PLAN.md numbered this V6 and V7 and said to do it first. It is being
-- done last instead, which is the most expensive order available: there are
-- now 192 settled bills, a stock ledger, two shifts' worth of cash movements
-- and a customer ledger to carry across rather than a handful of rows. The
-- argument for doing it first was exactly this, and it was right.
--
-- ---------------------------------------------------------------------------
-- NOT NULL from the start
--
-- ERD §3.1: a nullable tenant key becomes a permanent source of rows belonging
-- to nobody. Every column below is added, backfilled to branch 1 and made NOT
-- NULL in the same migration, so there is never a moment when a row can be
-- written without a branch.
--
-- ---------------------------------------------------------------------------
-- Branch implies company
--
-- company_id is not repeated on every table. Carrying both is denormalisation
-- that drifts; the join through branch is one hop and always correct.
-- ---------------------------------------------------------------------------

CREATE TABLE company (
    id      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(150) NOT NULL,
    name_en VARCHAR(150),
    tax_id  VARCHAR(50),

    act_yn  VARCHAR(1)   NOT NULL DEFAULT 'Y',
    reg_id  VARCHAR(50),
    reg_dtm TIMESTAMP,
    mod_id  VARCHAR(50),
    mod_dtm TIMESTAMP
);

CREATE TABLE branch (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT       NOT NULL,
    code       VARCHAR(20)  NOT NULL,
    name       VARCHAR(150) NOT NULL,
    name_en    VARCHAR(150),
    address    VARCHAR(500),
    phone      VARCHAR(30),

    act_yn     VARCHAR(1)   NOT NULL DEFAULT 'Y',
    reg_id     VARCHAR(50),
    reg_dtm    TIMESTAMP,
    mod_id     VARCHAR(50),
    mod_dtm    TIMESTAMP,

    CONSTRAINT fk_branch_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT uk_branch_code    UNIQUE (company_id, code)
);

-- ---------------------------------------------------------------------------
-- The shop that already exists
--
-- Named from the settings the receipt already prints, so the branch badge says
-- what the slips say rather than "Branch 1". COALESCE because a missing
-- setting must not stop the migration.
-- ---------------------------------------------------------------------------

