-- ---------------------------------------------------------------------------
-- Uniqueness becomes per-branch
--
-- Two shops each have a Table 01 and each have their own customer codes. A
-- constraint that spans the company would make the second branch's first
-- working day an argument with the database.
--
-- Invoice and return numbers stay unique across the company: they are drawn
-- from one sequence and a tax authority asking about INV-00231 should get one
-- answer.
-- ---------------------------------------------------------------------------

ALTER TABLE customer DROP CONSTRAINT uk_customer_code;
ALTER TABLE customer ADD CONSTRAINT uk_customer_code UNIQUE (branch_id, code);

-- ---------------------------------------------------------------------------
-- One open shift per cashier per branch
--
-- V14's key held the cashier's id; with branches it has to say which till, or
-- a cashier covering two shops could only ever open one drawer. The CHECK is
-- carried over unchanged in substance, including V16's explicit nullness.
-- ---------------------------------------------------------------------------

ALTER TABLE cash_shift DROP CONSTRAINT ck_shift_open_key;
ALTER TABLE cash_shift DROP CONSTRAINT uk_shift_one_open;

ALTER TABLE cash_shift ADD COLUMN open_branch_id BIGINT;
UPDATE cash_shift SET open_branch_id = branch_id WHERE status = 'OPEN';

ALTER TABLE cash_shift
    ADD CONSTRAINT uk_shift_one_open UNIQUE (open_branch_id, open_user_ref);

ALTER TABLE cash_shift
    ADD CONSTRAINT ck_shift_open_key CHECK (
        (status = 'OPEN'
            AND open_user_ref IS NOT NULL
            AND open_user_ref = user_ref
            AND open_branch_id IS NOT NULL
            AND open_branch_id = branch_id
            AND closed_at IS NULL
            AND declared_cash IS NULL)
     OR (status = 'CLOSED'
            AND open_user_ref IS NULL
            AND open_branch_id IS NULL
            AND closed_at IS NOT NULL
            AND declared_cash IS NOT NULL));

